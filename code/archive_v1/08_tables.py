def stars(p):
    return "***" if p < 0.01 else "**" if p < 0.05 else "*" if p < 0.10 else ""


def cell(row):
    if row is None or pd.isna(row["est"]):
        return ""
    return f"{row['est']:.3f}{stars(row['p'])}<br>({row['se']:.3f})"


def coef_table(df, models, terms, labels, extra_rows=None, colnames=None):
    head = "| | " + " | ".join(colnames or [f"({i+1})" for i in range(len(models))]) + " |"
    sep = "|---|" + "---|" * len(models)
    lines = [head, sep]
    for t in terms:
        cells = []
        for m in models:
            r = df[(df.model == m) & (df.term == t)]
            cells.append(cell(r.iloc[0]) if len(r) else "")
        lines.append(f"| {labels.get(t, t)} | " + " | ".join(cells) + " |")
    for lab, vals in (extra_rows or []):
        lines.append(f"| {lab} | " + " | ".join(vals) + " |")
    nrow = [str(int(df[df.model == m].n.iloc[0])) if len(df[df.model == m]) else "" for m in models]
    lines.append("| Observations | " + " | ".join(nrow) + " |")
    return "\n".join(lines)


def write(name, text, note=""):
    with open(os.path.join(MD, name + ".md"), "w") as f:
        f.write(text + ("\n\n" + note if note else "") + "\n")


